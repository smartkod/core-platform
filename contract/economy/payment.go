package economy

import (
	"context"
	"errors"
	"net/http"
)

// Payment-provider sentinels. They map to HTTP statuses in one place, like the
// rest of the economy errors.
var (
	// ErrProviderNotFound means no adapter is registered under that name.
	ErrProviderNotFound = errors.New("economy: payment provider not registered")
	// ErrProviderUnsupported means the adapter cannot do the requested
	// operation (a manual provider has no refund API, for example).
	ErrProviderUnsupported = errors.New("economy: operation not supported by provider")
	// ErrPaymentMismatch means the provider reported an amount or currency
	// that does not match the order. Fulfilling it would sell at the wrong
	// price, so it is refused.
	ErrPaymentMismatch = errors.New("economy: payment does not match the order")
	// ErrSignatureInvalid means an adapter could not verify a webhook. It maps
	// to 401 and nothing is recorded.
	ErrSignatureInvalid = errors.New("economy: webhook signature invalid")
	// ErrOrderNotFound hides whether another user's order exists.
	ErrOrderNotFound = errors.New("economy: order not found")
	// ErrOrderNotPayable means the order is not in a state the action accepts
	// (already fulfilled, expired, refunded).
	ErrOrderNotPayable = errors.New("economy: order is not payable in its current state")
	// ErrProductNotAvailable means the product is unknown or inactive.
	ErrProductNotAvailable = errors.New("economy: product not available")
	// ErrEntitlementNotFound is a stale entitlement id.
	ErrEntitlementNotFound = errors.New("economy: entitlement not found")
	// ErrIdempotencyRequired means the order request had no idempotency key.
	ErrIdempotencyRequired = errors.New("economy: idempotency key required")
	// ErrIdempotencyConflict means the key is already used by another user's
	// order. Returning that order would leak somebody else's purchase, so the
	// request is refused with 409 instead of replaying it.
	ErrIdempotencyConflict = errors.New("economy: idempotency key belongs to another user")
)

// ProviderCapabilities states what an adapter can do, so the order service can
// pick the right path without type-switching on adapters.
type ProviderCapabilities struct {
	// Webhook reports whether the provider calls back with signed events.
	Webhook bool
	// Refund reports whether Refund is implemented for real.
	Refund bool
	// SettlesImmediately reports that CreateCheckout already returns a paid
	// result (the test adapter), so no user action is awaited.
	SettlesImmediately bool
}

// CheckoutInput is what an adapter needs to start a payment. The amount is
// always the server's product price, never a client value.
type CheckoutInput struct {
	OrderID     string
	UserID      string
	ProductCode string
	ProductName string
	AmountMinor int64
	Currency    string
	Description string
	ReturnURL   string
	// ReferenceCode is generated by the order service so the operator and the
	// webhook both quote the same human-readable order id.
	ReferenceCode string
}

// CheckoutResult is the adapter's answer.
//
// Status is OrderPending for an asynchronous provider (the user must pay) or
// OrderPaid for one that settles inline. ReferenceCode is what the operator or
// webhook will quote back; ProviderRef is the adapter's own id.
type CheckoutResult struct {
	ProviderRef   string
	ReferenceCode string
	RedirectURL   string
	Instructions  string
	Status        string
}

// ProviderEvent is a verified webhook, normalised across adapters.
//
// EventID is the provider's own unique id: it is the deduplication key in
// payment_events, so a retried delivery is a no-op rather than a second
// fulfillment.
type ProviderEvent struct {
	EventID       string
	Type          string
	OrderID       string
	ReferenceCode string
	ProviderRef   string
	Status        string
	AmountMinor   int64
	Currency      string
	RawPayload    []byte
}

// RefundInput asks the provider to reverse (part of) a payment.
type RefundInput struct {
	PaymentID   string
	ProviderRef string
	AmountMinor int64
	Currency    string
	Reason      string
}

// RefundResult is the adapter's answer to a refund request.
type RefundResult struct {
	ProviderRef string
	Status      string
}

// PaymentProvider is the adapter boundary (L2.md 3.6).
//
// Adding a provider means adding a package that implements this interface and
// registering it in configuration; the wallet, orders, entitlements and the
// state machine do not change. That is the extensibility acceptance criterion.
type PaymentProvider interface {
	// Name is the stable identifier persisted in orders.provider.
	Name() string
	// Capabilities tells the service which path it may take.
	Capabilities() ProviderCapabilities
	// CreateCheckout starts a payment and returns where to send the user.
	CreateCheckout(ctx context.Context, in CheckoutInput) (CheckoutResult, error)
	// ParseWebhook verifies the signature and normalises the event.
	// ErrUnauthorized means the signature failed: nothing is recorded.
	ParseWebhook(r *http.Request) (ProviderEvent, error)
	// Refund reverses a payment at the provider.
	Refund(ctx context.Context, in RefundInput) (RefundResult, error)
}
